//function to allow for downlaoading the compare list for requirement 
window.downloadCompareList = function(){
  //pulls data from local storage and puts into an array
  const comparisonList = JSON.parse(localStorage.getItem("comparisonList")) || [];//if no vehicles, use and empty array
  //loops through the all vehicles in VEHICLES, if thier id is in the comparison list it keeps them in selected vehicles
  const selectedVehicles = VEHICLES.filter(v =>comparisonList.includes(v.id));

  //converts the JS to json string, null and 2 for spacing 
  const json = JSON.stringify(selectedVehicles, null, 2);

  //creates the file
  const download = new Blob([json], {type: "application/json"});//[json] is file content and type is json
  const url = URL.createObjectURL(download);//creates a temp url turning file to temp link

  const a = document.createElement("a");//sets a download link with <a> element
  a.href = url;//the <a> element links to the temp url for the file
  a.download = "comparison-list.json";//downloads the file 
  a.click();//when they click the link ^^^
}

