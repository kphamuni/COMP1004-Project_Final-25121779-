//Router for SPA functionaility
function router() {
  const path = route();//gets the url hash, removes hash, then decides which page to render"/brand/toyota" 
  const parts = path.split("/").filter(Boolean);

  //
  if (parts.length === 0) return renderHome();

  //"/brands"
  if (parts[0] === "brands") return renderBrands();

  //"/brand/:slug(brand)"
  if (parts[0] === "brand" && parts[1]) return renderBrandPage(parts[1]);

  //"/compare"
  if (parts[0] === "compare") return renderComparePage();

  //"/information"
  if (parts[0] === "information") return renderInfo();

  //"/vehicle/:id"
  if (parts[0] === "vehicle" && parts[1]) return renderVehiclePage(parts[1]);

  return renderNotFound();
}

window.addEventListener("hashchange", router);
