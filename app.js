function route() {
  return (location.hash || "#/").slice(1); //Gets rid of '#' from url hash, allows for easier routing/ cleaner path
}

function urlBuilder(str) {
  return str.toLowerCase().trim().replace(/\s+/g, "-");//Changes text to more url style. e.g. ' ' = '-' and uppercase becomes lower. E.g. A car like Toyota Yaris url would be toyota-yaris.
}

function linkToBrand(brandName) {//calls urlBuilder to build the url for browser search bar
  return `#/brand/${urlBuilder(brandName)}`;//e.g. brandname is called and converted to lowercase/dashes for brand/{brandname}
}

