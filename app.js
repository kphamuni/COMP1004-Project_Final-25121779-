//----------------LOGIC FOR BUTTON TO COMPARE + OTHERS-------------------------
function toggleCompare(vehicleId, button){
  let comparisonList = JSON.parse(localStorage.getItem("comparisonList")) || [];

  const isSelected = comparisonList.includes(vehicleId);

  if (isSelected){
    //Remove from list
    comparisonList = comparisonList.filter(id => id !== vehicleId);
  }
  else{
    //Only allows for 2 cars at most in the list
    if (comparisonList.length >= 2){
      return;
    }

    //Adding to list
    comparisonList.push(vehicleId);
  }

  localStorage.setItem("comparisonList", JSON.stringify(comparisonList));

  router();//reloading page
}

window.clearCompareList = function(){//window. makes function global to use for in-lin onclick calls
  localStorage.removeItem("comparisonList");//clears comparison list
  router();//reloads page
}

